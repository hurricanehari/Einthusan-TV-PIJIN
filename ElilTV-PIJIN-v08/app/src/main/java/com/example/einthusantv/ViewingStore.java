package com.example.einthusantv;

import android.content.Context;
import android.content.SharedPreferences;
import org.json.JSONArray;
import org.json.JSONObject;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

/** Device-local viewing history: separate profiles, one shared Einthusan session.
 * No passwords, session cookies, stream URLs or account tokens are saved here.
 */
public final class ViewingStore {
    private static final String PREF = "elil_profiles_v1";
    private static final String KEY = "state";
    private static final long MIN_WATCH_MS = 30000L;
    private static final double FINISHED_AT = .95;
    private final SharedPreferences preferences;
    private JSONObject state;

    public static final class Profile {
        public final String id, name;
        Profile(String id, String name){ this.id=id;this.name=name; }
    }
    public static final class Entry {
        public final Film film;
        public final long positionMs, durationMs, lastPlayed;
        public final boolean saved, hidden, completed, started, ultra;
        Entry(Film f, long p, long d, long time, boolean saved, boolean hidden,
              boolean complete, boolean started, boolean ultra){
            film=f;positionMs=p;durationMs=d;lastPlayed=time;this.saved=saved;
            this.hidden=hidden;completed=complete;this.started=started;this.ultra=ultra;
        }
        public int percent(){
            return durationMs > 0 ? (int)Math.min(100L,Math.max(0L,100L*positionMs/durationMs)) : 0;
        }
        public boolean canResume(){return started && !completed && positionMs>=MIN_WATCH_MS &&
            (durationMs<=0 || positionMs < durationMs * FINISHED_AT);}
        public long remainingMs(){return durationMs<=0 ? 0L : Math.max(0L,durationMs-positionMs);}
    }

    public ViewingStore(Context context){
        preferences=context.getApplicationContext().getSharedPreferences(PREF,Context.MODE_PRIVATE);
        try{state=new JSONObject(preferences.getString(KEY,"{}"));}catch(Exception e){state=new JSONObject();}
        initialise();
    }
    private static String key(Film f){return f.language+":"+f.id;}
    private void initialise(){
        JSONArray profiles=state.optJSONArray("profiles");
        if(profiles==null||profiles.length()==0){
            profiles=new JSONArray();
            JSONObject primary=new JSONObject();
            try{primary.put("id","primary");primary.put("name","My Profile");
                profiles.put(primary);state.put("profiles",profiles);state.put("active","primary");}
            catch(Exception ignored){}
        }
        // Rename only the original autogenerated label. Preserve the existing
        // profile ID and all associated watch history, progress and My List data.
        for(int i=0;i<profiles.length();i++){
            JSONObject profile=profiles.optJSONObject(i);
            if(profile!=null && "primary".equals(profile.optString("id")) &&
                "Primary".equals(profile.optString("name"))){
                try{profile.put("name","My Profile");}catch(Exception ignored){}
            }
        }
        if(state.optJSONObject("items")==null){try{state.put("items",new JSONObject());}catch(Exception ignored){}}
        String active=state.optString("active","primary");
        if(!profileExists(active)){
            JSONObject p=profiles.optJSONObject(0);
            try{state.put("active",p==null?"primary":p.optString("id","primary"));}catch(Exception ignored){}
        }
        save();
    }
    private void save(){preferences.edit().putString(KEY,state.toString()).apply();}
    private boolean profileExists(String id){for(Profile p:profiles())if(p.id.equals(id))return true;return false;}
    public synchronized List<Profile> profiles(){
        List<Profile> out=new ArrayList<>();JSONArray arr=state.optJSONArray("profiles");
        if(arr==null)return out;
        for(int i=0;i<arr.length();i++){
            JSONObject p=arr.optJSONObject(i);
            if(p!=null)out.add(new Profile(p.optString("id"),p.optString("name","Profile")));
        }
        return out;
    }
    public synchronized String activeId(){return state.optString("active","primary");}
    public synchronized String activeName(){
        String id=activeId();for(Profile p:profiles())if(p.id.equals(id))return p.name;
        return "My Profile";
    }
    public synchronized boolean switchTo(String id){
        if(!profileExists(id))return false;
        try{state.put("active",id);save();return true;}catch(Exception e){return false;}
    }
    public synchronized boolean addProfile(String name){
        if(name==null)return false;
        String cleaned=name.trim().replaceAll("\\s+"," ");
        if(cleaned.isEmpty()||cleaned.length()>24||profiles().size()>=6)return false;
        for(Profile p:profiles())if(p.name.equalsIgnoreCase(cleaned))return false;
        JSONObject profile=new JSONObject();
        try{String id=UUID.randomUUID().toString();profile.put("id",id);profile.put("name",cleaned);
            state.getJSONArray("profiles").put(profile);state.put("active",id);save();return true;
        }catch(Exception e){return false;}
    }
    /** Rename a profile without changing its ID or any saved viewing data. */
    public synchronized boolean renameProfile(String profileId,String name){
        if(name==null || !profileExists(profileId))return false;
        String cleaned=name.trim().replaceAll("\\s+"," ");
        if(cleaned.isEmpty() || cleaned.length()>24)return false;
        for(Profile p:profiles()){
            if(!p.id.equals(profileId) && p.name.equalsIgnoreCase(cleaned))return false;
        }
        JSONArray arr=state.optJSONArray("profiles");
        if(arr==null)return false;
        for(int i=0;i<arr.length();i++){
            JSONObject profile=arr.optJSONObject(i);
            if(profile!=null && profileId.equals(profile.optString("id"))){
                try{profile.put("name",cleaned);save();return true;}
                catch(Exception ignored){return false;}
            }
        }
        return false;
    }
    private JSONObject profileItems(String id,boolean create){
        JSONObject all=state.optJSONObject("items");if(all==null)return new JSONObject();
        JSONObject result=all.optJSONObject(id);
        if(result==null && create){result=new JSONObject();try{all.put(id,result);}catch(Exception ignored){}}
        return result==null?new JSONObject():result;
    }
    private JSONObject record(String profileId,Film film,boolean create){
        JSONObject items=profileItems(profileId,create), rec=items.optJSONObject(key(film));
        if(rec==null&&create){rec=new JSONObject();try{items.put(key(film),rec);}catch(Exception ignored){}}
        if(rec!=null&&create)putFilm(rec,film);
        return rec;
    }
    private static void putFilm(JSONObject r,Film f){
        try{r.put("id",f.id);r.put("language",f.language);r.put("title",f.title);
            r.put("poster",f.poster);r.put("synopsis",f.synopsis);
            r.put("detailUrl",f.detailUrl);r.put("quality",f.quality);r.put("badge",f.badge);
        }catch(Exception ignored){}
    }
    private static Entry parse(JSONObject r){
        if(r==null)return null;
        String id=r.optString("id"),language=r.optString("language");
        if(id.isEmpty()||language.isEmpty())return null;
        Film f=new Film(id,language,r.optString("title","Film"),r.optString("poster"),
            r.optString("synopsis"),r.optString("detailUrl"),r.optString("quality","shd"),r.optString("badge"));
        return new Entry(f,r.optLong("position",0),r.optLong("duration",0),r.optLong("lastPlayed",0),
            r.optBoolean("saved"),r.optBoolean("hidden"),r.optBoolean("completed"),
            r.optBoolean("started"),r.optBoolean("ultra"));
    }
    public synchronized Entry entry(Film f){return parse(record(activeId(),f,false));}
    public synchronized boolean isSaved(Film f){Entry e=entry(f);return e!=null&&e.saved;}
    public synchronized void setSaved(Film f,boolean value){
        JSONObject r=record(activeId(),f,true);
        try{r.put("saved",value);save();}catch(Exception ignored){}
    }
    public synchronized void removeFromContinue(Film f){
        JSONObject r=record(activeId(),f,true);
        try{r.put("hidden",true);save();}catch(Exception ignored){}
    }
    /** Called before playback so a deliberate replay makes an item eligible for Continue Watching again. */
    public synchronized void begin(String profileId,Film f,boolean ultra,boolean restart){
        if(!profileExists(profileId))return;
        JSONObject r=record(profileId,f,true);
        try{r.put("hidden",false);r.put("ultra",ultra);
            if(restart){r.put("position",0);r.put("completed",false);}
            save();
        }catch(Exception ignored){}
    }
    public synchronized void savePosition(String profileId,Film f,long position,long duration,boolean ultra,boolean ended){
        if(!profileExists(profileId))return;
        JSONObject r=record(profileId,f,true);
        long oldDuration=r.optLong("duration",0);
        long effectiveDuration=duration>0?duration:oldDuration;
        long safePosition=Math.max(0,position);
        if(effectiveDuration>0)safePosition=Math.min(effectiveDuration,safePosition);
        boolean completed=ended||(effectiveDuration>0 && safePosition >= effectiveDuration*FINISHED_AT);
        try{r.put("position",safePosition);r.put("duration",effectiveDuration);
            r.put("completed",completed);r.put("started",true);r.put("ultra",ultra);
            r.put("lastPlayed",System.currentTimeMillis());save();
        }catch(Exception ignored){}
    }
    private synchronized List<Entry> all(){
        JSONObject items=profileItems(activeId(),false);List<Entry> out=new ArrayList<>();
        JSONArray names=items.names();if(names==null)return out;
        for(int i=0;i<names.length();i++){
            Entry e=parse(items.optJSONObject(names.optString(i)));
            if(e!=null)out.add(e);
        }
        return out;
    }
    public synchronized List<Entry> continueWatching(){
        List<Entry> out=new ArrayList<>();for(Entry e:all())if(e.canResume()&&!e.hidden)out.add(e);
        Collections.sort(out,(a,b)->Long.compare(b.lastPlayed,a.lastPlayed));return out;
    }
    public synchronized List<Entry> myList(){
        List<Entry> out=new ArrayList<>();for(Entry e:all())if(e.saved)out.add(e);
        Collections.sort(out,(a,b)->Long.compare(b.lastPlayed,a.lastPlayed));return out;
    }
    public synchronized List<Entry> recentlyWatched(){
        List<Entry> out=new ArrayList<>();for(Entry e:all())if(e.started&&e.lastPlayed>0)out.add(e);
        Collections.sort(out,(a,b)->Long.compare(b.lastPlayed,a.lastPlayed));return out;
    }
}
